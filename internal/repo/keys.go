package repo

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"

	"fdroid-selfhost/internal/config"
)

const (
	keystoreFile = "keystore.p12"
	passFile     = "keystore.pass"
	keyAlias     = "repokey"
	configFile   = "config.yml"
)

// Runner runs an external command in dir and returns its combined output.
// It exists so tests can replace keytool and fdroid.
type Runner func(ctx context.Context, dir, name string, args ...string) ([]byte, error)

// ExecRunner is the production Runner.
func ExecRunner(ctx context.Context, dir, name string, args ...string) ([]byte, error) {
	cmd := exec.CommandContext(ctx, name, args...) //nolint:gosec // binaries come from trusted server config
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		return out, fmt.Errorf("%s %s: %w", name, strings.Join(args, " "), err)
	}
	return out, nil
}

// Setup prepares the data directory for fdroidserver: it creates the repo
// signing key on first run, (re)writes config.yml from the server
// configuration, and returns the key's SHA-256 fingerprint.
func Setup(ctx context.Context, cfg config.Config, run Runner) (string, error) {
	if err := os.MkdirAll(cfg.DataDir, 0o750); err != nil {
		return "", err
	}
	pass, err := keystorePass(cfg)
	if err != nil {
		return "", err
	}
	keystore := filepath.Join(cfg.DataDir, keystoreFile)
	if _, err := os.Stat(keystore); errors.Is(err, os.ErrNotExist) {
		if err := generateKeystore(ctx, cfg, run, pass); err != nil {
			return "", err
		}
	}

	apksigner := cfg.ApksignerPath
	if _, err := os.Stat(apksigner); err != nil {
		apksigner = "" // let fdroidserver search PATH / the Android SDK instead
	}
	yml := renderFdroidConfig(cfg, pass, apksigner)
	if err := os.WriteFile(filepath.Join(cfg.DataDir, configFile), []byte(yml), 0o600); err != nil {
		return "", err
	}

	out, err := run(ctx, cfg.DataDir, cfg.KeytoolBin,
		"-list", "-v", "-keystore", keystoreFile, "-alias", keyAlias, "-storepass", pass)
	if err != nil {
		return "", fmt.Errorf("reading key fingerprint: %w", err)
	}
	return ParseFingerprint(string(out))
}

// keystorePass returns the keystore password: from the environment, from
// the file written on a previous run, or freshly generated.
func keystorePass(cfg config.Config) (string, error) {
	if cfg.KeystorePass != "" {
		return cfg.KeystorePass, nil
	}
	path := filepath.Join(cfg.DataDir, passFile)
	if b, err := os.ReadFile(path); err == nil { //nolint:gosec // path is inside the configured data dir
		return strings.TrimSpace(string(b)), nil
	}
	if _, err := os.Stat(filepath.Join(cfg.DataDir, keystoreFile)); err == nil {
		return "", errors.New("keystore exists but its password is unknown: set KEYSTORE_PASS")
	}
	raw := make([]byte, 24)
	if _, err := rand.Read(raw); err != nil {
		return "", err
	}
	pass := hex.EncodeToString(raw)
	return pass, os.WriteFile(path, []byte(pass+"\n"), 0o600)
}

func generateKeystore(ctx context.Context, cfg config.Config, run Runner, pass string) error {
	_, err := run(ctx, cfg.DataDir, cfg.KeytoolBin,
		"-genkeypair", "-keystore", keystoreFile, "-storetype", "PKCS12",
		"-alias", keyAlias, "-keyalg", "RSA", "-keysize", "4096",
		"-sigalg", "SHA256withRSA", "-validity", "10000",
		"-storepass", pass, "-keypass", pass,
		"-dname", "CN=fdroid-selfhost, OU=F-Droid, O=Self-hosted")
	if err != nil {
		return fmt.Errorf("creating repo signing key: %w", err)
	}
	return nil
}

// renderFdroidConfig returns the contents of fdroidserver's config.yml.
// Values go through JSON encoding, which is valid YAML double-quoted syntax.
func renderFdroidConfig(cfg config.Config, pass, apksigner string) string {
	quote := func(s string) string {
		b, _ := json.Marshal(s)
		return string(b)
	}
	lines := []string{
		"# Generated by fdroid-selfhost on every start. Edit the environment, not this file.",
		"repo_url: " + quote(cfg.RepoURL()),
		"repo_name: " + quote(cfg.RepoName),
		"repo_description: " + quote(cfg.RepoDescription),
		"repo_keyalias: " + quote(keyAlias),
		"keystore: " + quote(keystoreFile),
		"keystorepass: " + quote(pass),
		"keypass: " + quote(pass),
		"keydname: " + quote("CN=fdroid-selfhost, OU=F-Droid, O=Self-hosted"),
	}
	if apksigner != "" {
		lines = append(lines, "apksigner: "+quote(apksigner))
	}
	return strings.Join(lines, "\n") + "\n"
}

var sha256Re = regexp.MustCompile(`SHA256:\s*([0-9A-Fa-f:]{95})`)

// ParseFingerprint extracts the certificate SHA-256 from `keytool -list -v`
// output and formats it the way F-Droid expects: upper-case hex, no colons.
func ParseFingerprint(keytoolOutput string) (string, error) {
	m := sha256Re.FindStringSubmatch(keytoolOutput)
	if m == nil {
		return "", errors.New("no SHA256 fingerprint in keytool output")
	}
	return strings.ToUpper(strings.ReplaceAll(m[1], ":", "")), nil
}
